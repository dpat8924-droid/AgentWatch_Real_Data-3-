def create_ui_server(args, resources, scenarios):
    """Bind to this computer; serve only this session's completed result folders."""
    by_id = {scenario["id"]: scenario for scenario in scenarios}
    catalog = ui_scenarios(resources, scenarios)
    token = uuid4().hex
    run_folders = {}
    selected = args.scenario or ("IH02" if "IH02" in by_id else scenarios[0]["id"])

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, format, *arguments):
            pass

        def reply(self, status, content, content_type="application/json; charset=utf-8", attachment=False):
            if isinstance(content, (dict, list)):
                content = json.dumps(content, ensure_ascii=False).encode("utf-8")
            elif isinstance(content, str):
                content = content.encode("utf-8")
            self.send_response(status)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(content)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("Referrer-Policy", "no-referrer")
            if attachment:
                self.send_header("Content-Disposition", 'attachment; filename="scenario_data.csv"')
            self.end_headers()
            self.wfile.write(content)

        def valid_host(self):
            expected = f"127.0.0.1:{self.server.server_port}"
            if self.headers.get("Host") != expected:
                self.reply(403, {"error": "Use the local address printed in the AgentWatch terminal."})
                return False
            return True

        def do_GET(self):
            if not self.valid_host():
                return
            route = urlsplit(self.path)
            if route.path == "/":
                self.reply(200, control_page(token, selected, args.approval), "text/html; charset=utf-8")
            elif route.path == "/api/scenarios":
                self.reply(200, {"scenarios": catalog})
            elif route.path == "/api/data":
                identifier = parse_qs(route.query).get("scenario", [""])[0]
                scenario = by_id.get(identifier)
                if scenario is None:
                    self.reply(404, {"error": "Choose an available scenario."})
                    return
                resource = resources[scenario["action"]["resource_id"]]
                self.reply(200, resource.get("content", ""), "text/plain; charset=utf-8", attachment=True)
            elif route.path.startswith("/runs/"):
                parts = unquote(route.path).split("/", 3)
                folder = run_folders.get(parts[2]) if len(parts) == 4 else None
                target = (folder / parts[3]).resolve() if folder else None
                if target is None or not target.is_relative_to(folder) or not target.is_file():
                    self.reply(404, {"error": "This result file is not available."})
                    return
                content_type = mimetypes.guess_type(target.name)[0] or "application/octet-stream"
                self.reply(200, target.read_bytes(), content_type)
            elif route.path == "/favicon.ico":
                self.reply(204, b"")
            else:
                self.reply(404, {"error": "Page not found."})

        def do_POST(self):
            if not self.valid_host():
                return
            origin = self.headers.get("Origin")
            if (origin and origin != f"http://127.0.0.1:{self.server.server_port}") or self.headers.get("X-AgentWatch-Token") != token:
                self.reply(403, {"error": "Refresh the AgentWatch control screen and try again."})
                return
            if urlsplit(self.path).path != "/api/run":
                self.reply(404, {"error": "Page not found."})
                return
            try:
                length = int(self.headers.get("Content-Length", "0"))
                if not 0 < length <= 4096 or self.headers.get_content_type() != "application/json":
                    raise ValueError("Choose a scenario and approval response using the controls.")
                request = json.loads(self.rfile.read(length))
                if not isinstance(request, dict) or not isinstance(request.get("scenario"), str):
                    raise ValueError("Choose an available scenario.")
                scenario = by_id.get(request["scenario"])
                if scenario is None or request.get("approval") not in ("approve", "deny"):
                    raise ValueError("Choose an available scenario and approval response.")
            except (ValueError, UnicodeError) as error:
                self.reply(400, {"error": str(error)})
                return
            try:
                settings = copy.copy(args)
                settings.approval, settings.rounds = request["approval"], 1
                folder, metadata, rows, _ = run_experiment(settings, resources, [scenario])
                run_folders[metadata["run_id"]] = folder
                base = f"/runs/{metadata['run_id']}/"
                results = []
                for row in sorted(rows, key=lambda item: STRATEGIES.index(item["strategy"])):
                    results.append({
                        "strategy": row["strategy"], "decision": row["actual_initial_decision"],
                        "approval": row["approval_status"], "executed": row["executed"],
                        "reason": row["reason"], "outcome": row["outcome"],
                        "rule": row["decision_rule"], "rule_detail": row["decision_detail"],
                        "checks": json.loads(row["rule_checks"]), "rule_evidence_html": rule_evidence(row),
                        "file_exists_after": row["file_exists_after"],
                        **{label: base + row[key] if row[key] else "" for label, key in (("before", "before_file"), ("after", "after_file"), ("staged", "staged_file"), ("record", "execution_record"))},
                    })
                self.reply(200, {"scenario": scenario["id"], "approval": settings.approval,
                                 "approval_used": any(row["approval_requested"] for row in rows),
                                 "completed_at": metadata["completed_at_utc"], "run_id": metadata["run_id"],
                                 "report": base + "report.html", "results": results})
            except (OSError, ValueError, KeyError, sqlite3.Error) as error:
                self.reply(500, {"error": f"The test could not finish: {error}"})

    return ThreadingHTTPServer(("127.0.0.1", 0), Handler)


