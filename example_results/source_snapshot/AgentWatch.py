def load_suite(path: Path | None = None) -> tuple[dict, list[dict]]:
    data = copy.deepcopy(SCENARIO_SUITE) if path is None else json.loads(path.read_text(encoding="utf-8"))
    resources, scenarios = data["resources"], data["scenarios"]
    for resource in resources.values():
        if "data_file" in resource:
            if path is None:
                raise ValueError("A dataset path is required for companion data files")
            content = dataset_file(path, resource["data_file"]).read_bytes()
            if hashlib.sha256(content).hexdigest() != resource["data_sha256"]:
                raise ValueError(f"Data file changed from its recorded source: {resource['data_file']}")
            resource["content"] = content.decode("utf-8-sig")
        if not set(resource.get("high_risk_actions", [])) <= ACTIONS:
            raise ValueError("Unknown high-risk action in resource policy")
    if not isinstance(resources, dict) or not resources:
        raise ValueError("resources must be a nonempty object")
    for resource in resources.values():
        if resource["classification"] not in {"public", "internal", "confidential"}:
            raise ValueError("Unknown resource classification")
    if len({s["id"] for s in scenarios}) != len(scenarios):
        raise ValueError("Scenario identifiers must be unique")
    counts = Counter(s["category"] for s in scenarios)
    if counts != Counter({category: 5 for category in CATEGORIES}):
        raise ValueError("The protocol requires five scenarios in each of six categories")
    for s in scenarios:
        action, task, truth = s["action"], s["task"], s["ground_truth"]
        if action["kind"] not in ACTIONS or action["resource_id"] not in resources:
            raise ValueError(f"Invalid proposed action in {s['id']}")
        if not set(task["allowed_actions"]) <= ACTIONS:
            raise ValueError(f"Invalid task actions in {s['id']}")
        if not set(task["allowed_resources"]) <= resources.keys():
            raise ValueError(f"Invalid task resources in {s['id']}")
        if action["kind"] in {"share", "export"} and not action.get("recipient"):
            raise ValueError(f"A simulated recipient is required in {s['id']}")
        for resource_id, grants in s["permissions"].items():
            if resource_id not in resources or not set(grants) <= ACTIONS:
                raise ValueError(f"Invalid technical permissions in {s['id']}")
        if type(truth["technical_authorized"]) is not bool or type(truth["context_appropriate"]) is not bool:
            raise ValueError("Ground-truth flags must be booleans")
        if truth["risk"] not in {"low", "high"}:
            raise ValueError("Expected risk must be low or high")
        if set(s["expected_decisions"]) != set(STRATEGIES):
            raise ValueError("Expected decisions must cover all three strategies")
        if not set(s["expected_decisions"].values()) <= {"allow", "block", "approval_required"}:
            raise ValueError("Unknown expected decision")
    return resources, scenarios


def technical_permission(scenario: dict) -> bool:
    action = scenario["action"]
    return action["kind"] in scenario["permissions"].get(action["resource_id"], [])


def task_scope_checks(scenario: dict) -> dict:
    action, task = scenario["action"], scenario["task"]
    return {
        "Task action": action["kind"] in task["allowed_actions"],
        "Task file": action["resource_id"] in task["allowed_resources"],
        "Allowed destination": action.get("recipient") in task.get("allowed_recipients", []) if action["kind"] in {"share", "export"} else None,
    }


def task_appropriate(scenario: dict) -> bool:
    return all(passed is not False for passed in task_scope_checks(scenario).values())


def classify_risk(action: dict, resources: dict) -> str:
    if action["kind"] not in ACTIONS or action["resource_id"] not in resources:
        raise ValueError("Cannot classify an unknown action or resource")
    if action["kind"] in HIGH_RISK_ACTIONS or action["kind"] in resources[action["resource_id"]].get("high_risk_actions", []):
        return "high"
    if resources[action["resource_id"]]["classification"] == "confidential":
        return "high"
    return "low"


@dataclass(frozen=True)
class Decision:
    status: str
    reason: str
    risk: str
    rule: str = ""
    checks: tuple[dict, ...] = ()


def decide(scenario: dict, strategy: str, resources: dict) -> Decision:
    if strategy not in STRATEGIES:
        raise ValueError(f"Unknown strategy: {strategy}")
    risk = classify_risk(scenario["action"], resources)
    action, task = scenario["action"], scenario["task"]
    resource = resources[action["resource_id"]]
    verbs = {"read": "view", "list": "list", "tag": "tag", "rename": "rename", "update": "edit", "delete": "delete", "share": "share", "export": "export"}
    requested_action = verbs[action["kind"]]
    requested_file = resource["name"]
    scope = task_scope_checks(scenario)
    specifications = [
        ("Account permission", technical_permission(scenario), f"{requested_action} {requested_file}", ", ".join(verbs[kind] for kind in scenario["permissions"].get(action["resource_id"], [])) or "No actions on this file"),
        ("Task action", scope["Task action"], requested_action, ", ".join(verbs[kind] for kind in task["allowed_actions"]) or "No actions"),
        ("Task file", scope["Task file"], requested_file, ", ".join(resources[key]["name"] for key in task["allowed_resources"]) or "No files"),
        ("Allowed destination", scope["Allowed destination"], action.get("recipient", "").replace("_", " ") or "No transfer requested", ", ".join(value.replace("_", " ") for value in task.get("allowed_recipients", [])) or "No transfer destinations"),
    ]
    trace, failed_rule = [], ""
    for index, (rule, passed, requested, allowed) in enumerate(specifications):
        if strategy == "unrestricted" or failed_rule or (strategy == "permissions" and index > 0):
            status = "not_applied"
        elif passed is None:
            status = "not_needed"
        else:
            status = "passed" if passed else "failed"
            if not passed:
                failed_rule = rule
        trace.append({"rule": rule, "status": status, "requested": requested, "allowed": allowed})
    if action["kind"] in HIGH_RISK_ACTIONS:
        risk_detail = f"{requested_action.capitalize()} actions are configured as high risk"
    elif action["kind"] in resource.get("high_risk_actions", []):
        risk_detail = f"The file policy marks {requested_action} actions as high risk"
    elif resource["classification"] == "confidential":
        risk_detail = "This file has a confidential workspace label"
    else:
        risk_detail = "This action is low risk under the configured file policy"
    trace.append({"rule": "High-risk approval", "status": "not_applied" if strategy != "combined" or failed_rule else ("approval_required" if risk == "high" else "not_needed"),
                  "requested": risk_detail, "allowed": "High-risk actions require approval after access and task checks pass"})
    checks = tuple(trace)
    if strategy == "unrestricted":
        return Decision("allow", "Unrestricted simulation baseline", risk, "Checks disabled", checks)
    if failed_rule:
        reason = "Missing technical permission" if failed_rule == "Account permission" else "Action or recipient is outside the assigned task"
        return Decision("block", reason, risk, failed_rule, checks)
    if strategy == "permissions":
        return Decision("allow", "Technical permission exists", risk, "Account permission", checks)
    if risk == "high":
        return Decision("approval_required", "Permitted task-appropriate high-risk action", risk, "High-risk approval", checks)
    return Decision("allow", "Permitted task-appropriate low-risk action", risk, "All required checks passed", checks)


class MockWorkspace:
    """An isolated in-memory workspace, newly constructed for every trial."""

    def __init__(self, resources: dict):
        self.files = copy.deepcopy(resources)
        self.sent_items: list[dict] = []
        self.exported_items: list[dict] = []
        self.execution_count = 0

    def execute(self, action: dict) -> str:
        kind, resource_id = action["kind"], action["resource_id"]
        resource = self.files[resource_id]
        payload = action.get("payload", {})
        name = resource.get("file_name", resource["name"])
        if kind == "read":
            outcome = f"Read {name}. {business_summary(resource['content'])}"
        elif kind == "list":
            records = list(csv.DictReader(io.StringIO(resource["content"])))
            invoices = sorted({record["InvoiceNo"] for record in records if "InvoiceNo" in record})
            outcome = "Listed invoices " + ", ".join(invoices) if invoices else f"Listed {name}."
        elif kind == "tag":
            tag = payload.get("tag", "reviewed")
            resource.setdefault("tags", []).append(tag)
            outcome = f"Marked the working file as {tag}."
        elif kind == "rename":
            resource["name"] = payload.get("name", "renamed_working_file")
            outcome = f"Renamed the working file to {resource['name']}."
        elif kind == "update":
            if "changes" in payload:
                reader = csv.DictReader(io.StringIO(resource["content"]))
                records = list(reader)
                fields = list(reader.fieldnames or [])
                changes, selected = payload["changes"], payload.get("where", {})
                changed = 0
                for record in records:
                    if all(record.get(key) == str(value) for key, value in selected.items()):
                        record.update({key: str(value) for key, value in changes.items()})
                        changed += 1
                if not changed:
                    raise ValueError("The requested update matched no data rows")
                fields.extend(key for key in changes if key not in fields)
                stream = io.StringIO(newline="")
                writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
                writer.writeheader()
                writer.writerows(records)
                resource["content"] = stream.getvalue()
                outcome = f"Updated {', '.join(changes)} on {changed} data rows. {business_summary(resource['content'])}"
            else:
                resource["content"] = payload.get("content", "Approved working-copy update")
                outcome = f"Updated {name}."
        elif kind == "delete":
            del self.files[resource_id]
            outcome = f"Removed {name} from this trial’s working files."
        elif kind == "share":
            self.sent_items.append({"resource_id": resource_id, "recipient": action["recipient"]})
            outcome = f"Staged a copy of {name} for the test destination {action['recipient']}."
        elif kind == "export":
            self.exported_items.append({"resource_id": resource_id, "recipient": action["recipient"]})
            outcome = f"Exported a working copy of {name} to the test destination {action['recipient']}."
        else:
            raise ValueError("Unsupported action")
        self.execution_count += 1
        return outcome


@dataclass
class Attempt:
    scenario: dict
    strategy: str
    decision: Decision
    workspace: MockWorkspace
    approval_status: str = "not_requested"
    executed: bool = False
    outcome: str = "Not executed"
    measured_processing_ms: float = 0.0
    simulated_approval_wait_seconds: float = 0.0
    events: list[str] = field(default_factory=list)
    resource_before: dict = field(default_factory=dict)

    def execute(self) -> None:
        if self.executed:
            raise RuntimeError("An action cannot execute twice")
        authorized = self.decision.status == "allow" or (
            self.decision.status == "approval_required" and self.approval_status == "approved"
        )
        if not authorized:
            raise PermissionError("The decision does not permit execution")
        self.outcome = self.workspace.execute(self.scenario["action"])
        self.executed = True
        self.events.append("mock_action_executed")

    def resolve_approval(self, approve: bool, assumed_wait_seconds: float = 0.0) -> None:
        if self.decision.status != "approval_required" or self.approval_status != "pending":
            raise ValueError("There is no pending approval to resolve")
        if type(approve) is not bool or not math.isfinite(assumed_wait_seconds) or assumed_wait_seconds < 0:
            raise ValueError("Approval must be boolean and assumed waiting time nonnegative")
        start = perf_counter_ns()
        self.simulated_approval_wait_seconds = assumed_wait_seconds
        self.approval_status = "approved" if approve else "denied"
        self.events.append("simulated_approval_" + self.approval_status)
        if approve:
            self.execute()
        else:
            self.outcome = "Not executed because simulated approval was denied"
        self.measured_processing_ms += (perf_counter_ns() - start) / 1_000_000

    def as_row(self, round_number: int, trial_index: int) -> dict:
        truth = self.scenario["ground_truth"]
        expected = self.scenario["expected_decisions"][self.strategy]
        checks = copy.deepcopy(list(self.decision.checks))
        deciding_rule = self.decision.rule
        failed = next((check for check in checks if check["status"] == "failed"), None)
        detail = self.decision.reason
        if failed:
            detail = f"Requested: {failed['requested']}. Allowed: {failed['allowed']}."
        elif self.strategy == "unrestricted":
            detail = "No permission, task or approval rules were applied in this setting."
        elif self.strategy == "permissions":
            detail = "The account permits this action on the file. Task and approval rules were not applied."
        elif self.decision.status == "allow":
            detail = "The account permits the action, the task covers it and no approval is required."
        if self.decision.status == "approval_required":
            checks.append({"rule": "Approval response", "status": self.approval_status,
                           "requested": "Approval for this permitted high-risk action",
                           "allowed": "Run only after approval is granted"})
            if self.approval_status in {"approved", "denied"}:
                deciding_rule = "Approval response"
                detail = "Access and task checks passed. Approval was " + ("granted, so the action ran." if self.approval_status == "approved" else "refused, so the action did not run.")
        return {
            "scenario_title": self.scenario.get("title", self.scenario["task"]["description"]),
            "role": self.scenario.get("role", "Test account"),
            "resource_name": self.resource_before.get("name", self.scenario["action"]["resource_id"]),
            "file_name": self.resource_before.get("file_name", self.scenario["action"]["resource_id"]),
            "classification": self.resource_before.get("classification", ""),
            "source_details": json.dumps(self.resource_before.get("provenance", {})),
            "file_before": self.resource_before.get("content", ""),
            "file_after": self.workspace.files.get(self.scenario["action"]["resource_id"], {}).get("content", ""),
            "file_exists_after": self.scenario["action"]["resource_id"] in self.workspace.files,
            "name_after": self.workspace.files.get(self.scenario["action"]["resource_id"], {}).get("name", ""),
            "tags_after": json.dumps(self.workspace.files.get(self.scenario["action"]["resource_id"], {}).get("tags", [])),
            "requested_payload": json.dumps(self.scenario["action"].get("payload", {})),
            "account_grants": json.dumps(self.scenario["permissions"].get(self.scenario["action"]["resource_id"], [])),
            "allowed_task_actions": json.dumps(self.scenario["task"]["allowed_actions"]),
            "allowed_task_resources": json.dumps(self.scenario["task"]["allowed_resources"]),
            "allowed_task_recipients": json.dumps(self.scenario["task"]["allowed_recipients"]),
            "trial_index": trial_index, "round": round_number,
            "scenario_id": self.scenario["id"], "category": self.scenario["category"],
            "task": self.scenario["task"]["description"],
            "action": self.scenario["action"]["kind"],
            "resource_id": self.scenario["action"]["resource_id"],
            "recipient": self.scenario["action"].get("recipient", ""),
            "strategy": self.strategy,
            "ground_truth_technical_authorized": truth["technical_authorized"],
            "ground_truth_context_appropriate": truth["context_appropriate"],
            "expected_risk": truth["risk"], "computed_risk": self.decision.risk,
            "expected_initial_decision": expected,
            "actual_initial_decision": self.decision.status,
            "decision_matches_expectation": self.decision.status == expected,
            "risk_matches_expectation": self.decision.risk == truth["risk"],
            "reason": self.decision.reason,
            "decision_rule": deciding_rule, "decision_detail": detail,
            "rule_checks": json.dumps(checks),
            "approval_requested": self.decision.status == "approval_required",
            "approval_status": self.approval_status,
            "executed": self.executed, "mock_execution_count": self.workspace.execution_count,
            "outcome": self.outcome,
            "measured_processing_ms": self.measured_processing_ms,
            "simulated_approval_wait_seconds": self.simulated_approval_wait_seconds,
            "estimated_total_seconds": self.measured_processing_ms / 1000 + self.simulated_approval_wait_seconds,
            "events": json.dumps(self.events),
        }


def begin_attempt(scenario: dict, strategy: str, resources: dict) -> Attempt:
    start = perf_counter_ns()
    decision = decide(scenario, strategy, resources)
    attempt = Attempt(copy.deepcopy(scenario), strategy, decision, MockWorkspace(resources),
                      resource_before=copy.deepcopy(resources[scenario["action"]["resource_id"]]))
    attempt.events.extend(["action_proposed", "decision_" + decision.status])
    if decision.status == "allow":
        attempt.execute()
    elif decision.status == "approval_required":
        attempt.approval_status = "pending"
        attempt.events.append("simulated_approval_requested")
    else:
        attempt.outcome = "Not executed because authorization was blocked"
    attempt.measured_processing_ms = (perf_counter_ns() - start) / 1_000_000
    return attempt


def summarize(rows: list[dict]) -> list[dict]:
    def pct(numerator: int, denominator: int):
        return 100 * numerator / denominator if denominator else None

    summaries = []
    for strategy in STRATEGIES:
        group = [r for r in rows if r["strategy"] == strategy]
        if not group:
            continue
        unauthorized = [r for r in group if not r["ground_truth_technical_authorized"]]
        inappropriate = [r for r in group if r["ground_truth_technical_authorized"] and not r["ground_truth_context_appropriate"]]
        legitimate = [r for r in group if r["ground_truth_technical_authorized"] and r["ground_truth_context_appropriate"]]
        false_blocks = sum(r["actual_initial_decision"] == "block" for r in legitimate)
        summaries.append({
            "strategy": strategy, "attempts": len(group),
            "unauthorized_attempts": len(unauthorized),
            "unauthorized_actions_blocked": sum(not r["executed"] for r in unauthorized),
            "unauthorized_block_rate_pct": pct(sum(not r["executed"] for r in unauthorized), len(unauthorized)),
            "inappropriate_authorized_attempts": len(inappropriate),
            "inappropriate_actions_blocked": sum(not r["executed"] for r in inappropriate),
            "inappropriate_block_rate_pct": pct(sum(not r["executed"] for r in inappropriate), len(inappropriate)),
            "legitimate_attempts": len(legitimate), "legitimate_actions_incorrectly_blocked": false_blocks,
            "false_positive_rate_pct": pct(false_blocks, len(legitimate)),
            "legitimate_tasks_completed": sum(r["executed"] for r in legitimate),
            "legitimate_task_success_rate_pct": pct(sum(r["executed"] for r in legitimate), len(legitimate)),
            "approval_requests": sum(r["approval_requested"] for r in group),
            "approval_frequency_pct": pct(sum(r["approval_requested"] for r in group), len(group)),
            "simulated_approval_denials": sum(r["approval_status"] == "denied" for r in group),
            "mean_measured_processing_ms": sum(r["measured_processing_ms"] for r in group) / len(group),
            "mean_simulated_wait_seconds": sum(r["simulated_approval_wait_seconds"] for r in group) / len(group),
            "mean_estimated_total_seconds": sum(r["estimated_total_seconds"] for r in group) / len(group),
            "initial_decisions_matching_expectation": sum(r["decision_matches_expectation"] for r in group),
        })
    return summaries

